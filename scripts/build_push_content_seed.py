def clean_text(value):
    value = re.sub(r"<br\s*/?>", "\n", value, flags=re.I)
    value = html.unescape(value)
    return re.sub(r"\\([\\`*_{}\[\]()#+\-.!])", r"\1", value).strip()


def classify(content_no):
    if content_no.startswith(("AM-", "NOON-", "PM-")):
        return "greeting", "GREETING_" + content_no.split("-")[1]
    if content_no.startswith("W-"):
        scene = re.sub(r"-\d+$", "", content_no[2:]).replace("-", "_")
        return "weather", "WEATHER_" + scene
    if content_no.startswith("DIARY-"):
        return "diary", "DIARY_READY"
    return "recall", "RECALL_" + content_no.split("-")[1]


def read_existing(zip_path, manifest_path):
    with open(manifest_path, encoding="utf-8-sig", newline="") as file:
        image_rows = list(csv.DictReader(file))
    image_map = {}
    for row in image_rows:
        if not row["status"].startswith("UPLOADED_VERIFIED"):
            continue
        image_map.setdefault(row["content_no"], []).append({
            "object_key": row["object_key"],
            "sha256": row["sha256"],
            "size_bytes": int(row["size_bytes"]),
        })

    result = []
    with zipfile.ZipFile(zip_path) as archive:
        markdown_name = next(
            name for name in archive.namelist() if name.endswith(".md")
        )
        markdown = archive.read(markdown_name).decode("utf-8")
    for line in markdown.splitlines():
        if not line.startswith("|"):
            continue
        cells = line.strip().strip("|").split("|")
        if len(cells) < 3:
            continue
        content_no = clean_text(cells[0])
        if not re.fullmatch(r"(?:AM|NOON|PM|W|DIARY|RECALL)-[A-Z0-9-]+", content_no):
            continue
        push_type, delivery_scene = classify(content_no)
        result.append({
            "content_no": content_no,
            "push_type": push_type,
            "delivery_scene": delivery_scene,
            "title": clean_text(cells[1]),
            "body": clean_text(cells[2]),
            "enabled": True,
            "images": image_map.get(content_no, []),
        })
    return result


def build_greeting_additions(existing_content):
    existing_counts = {}
    for item in existing_content:
        if item["push_type"] == "greeting":
            scene = item["delivery_scene"]
            existing_counts[scene] = existing_counts.get(scene, 0) + 1
    result = []
    for scene, profile in GREETING_PROFILES.items():
        prefix, topic, scene_text, preparation, action = profile
        current_count = existing_counts.get(scene, 0)
        for number in range(current_count + 1, 15):
            pattern_index = number - current_count - 1
            result.append({
                "content_no": "{}-{:02d}".format(prefix, number),
                "push_type": "greeting",
                "delivery_scene": scene,
                "title": GREETING_TITLE_PATTERNS[pattern_index].format(topic=topic),
                "body": GREETING_BODY_PATTERNS[pattern_index].format(
                    scene=scene_text,
                    prep=preparation,
                    action=action,
                ),
                "enabled": True,
                "images": [],
            })
    return result


def build_weather_additions():
    result = []
    for category, values in WEATHER_ADDITIONS.items():
        if not (len(values["titles"]) == len(values["advice"]) == len(values["care"]) == 10):
            raise ValueError("weather copy count mismatch for " + category)
        for index in range(10):
            result.append({
                "content_no": "W-{}-{:02d}".format(category.replace("_", "-"), index + 5),
                "push_type": "weather",
                "delivery_scene": "WEATHER_" + category,
                "title": values["titles"][index],
                "body": values["advice"][index] + values["care"][index],
                "enabled": True,
                "images": [],
            })
    return result


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--zip", required=True)
    parser.add_argument("--manifest", required=True)
    parser.add_argument("--output", required=True)
    args = parser.parse_args()

    existing = read_existing(args.zip, args.manifest)
    content = (
        existing
        + build_greeting_additions(existing)
        + build_weather_additions()
    )
    ids = [item["content_no"] for item in content]
    if len(ids) != len(set(ids)):
        raise ValueError("duplicate content number")
    with open(args.output, "w", encoding="utf-8") as file:
        json.dump(content, file, ensure_ascii=False, indent=2)
        file.write("\n")
    print("generated {} contents with {} images".format(
        len(content), sum(len(item["images"]) for item in content)
    ))


if __name__ == "__main__":
    main()
